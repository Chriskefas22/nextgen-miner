create or replace function public.nextgen_purchase_miner(p_miner_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid:=auth.uid(); m nextgen_miner_catalog%rowtype; w nextgen_wallets%rowtype; new_id bigint;
begin
 if uid is null then raise exception 'AUTH_REQUIRED'; end if;
 select * into m from nextgen_miner_catalog where id=p_miner_id and enabled=true for update;
 if not found then raise exception 'MINER_NOT_FOUND'; end if;
 if exists(select 1 from nextgen_user_miners where user_id=uid and miner_id=p_miner_id) then raise exception 'ALREADY_OWNED'; end if;
 if m.base_price_diamond>0 then
   select * into w from nextgen_wallets where user_id=uid for update;
   if not found or w.diamond_balance<m.base_price_diamond then raise exception 'INSUFFICIENT_DIAMOND'; end if;
   update nextgen_wallets set diamond_balance=diamond_balance-m.base_price_diamond,updated_at=now() where user_id=uid;
 else
   if exists(select 1 from nextgen_user_miners where user_id=uid and miner_id=p_miner_id) then raise exception 'STARTER_ALREADY_CLAIMED'; end if;
 end if;
 insert into nextgen_user_miners(user_id,miner_id,current_level,total_spent_diamond) values(uid,p_miner_id,1,m.base_price_diamond) returning id into new_id;
 insert into nextgen_transactions(user_id,tx_type,diamond_delta,reference_id,note) values(uid,'miner_purchase',-m.base_price_diamond,new_id::text,'Miner activation');
 return jsonb_build_object('ok',true,'user_miner_id',new_id,'miner_id',p_miner_id,'level',1,'hashrate',m.base_hashrate);
end $$;
revoke all on function public.nextgen_purchase_miner(bigint) from public,anon; grant execute on function public.nextgen_purchase_miner(bigint) to authenticated;
