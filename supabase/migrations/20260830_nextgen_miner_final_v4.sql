create or replace function public.nextgen_upgrade_miner(p_user_miner_id bigint)
returns jsonb language plpgsql security definer set search_path=public as $$
declare uid uuid := auth.uid(); um nextgen_user_miners%rowtype; lvl nextgen_miner_levels%rowtype; w nextgen_wallets%rowtype;
begin
 if uid is null then raise exception 'AUTH_REQUIRED'; end if;
 select * into um from nextgen_user_miners where id=p_user_miner_id and user_id=uid for update;
 if not found then raise exception 'MINER_NOT_FOUND'; end if;
 if um.current_level>=10 then raise exception 'MAX_LEVEL'; end if;
 select * into lvl from nextgen_miner_levels where miner_id=um.miner_id and level=um.current_level+1;
 select * into w from nextgen_wallets where user_id=uid for update;
 if not found then raise exception 'WALLET_NOT_FOUND'; end if;
 if w.diamond_balance<lvl.upgrade_price_diamond then raise exception 'INSUFFICIENT_DIAMOND'; end if;
 update nextgen_wallets set diamond_balance=diamond_balance-lvl.upgrade_price_diamond,updated_at=now() where user_id=uid;
 update nextgen_user_miners set current_level=lvl.level,total_spent_diamond=total_spent_diamond+lvl.upgrade_price_diamond,last_upgrade_at=now() where id=um.id;
 insert into nextgen_transactions(user_id,tx_type,diamond_delta,reference_id,note) values(uid,'miner_upgrade',-lvl.upgrade_price_diamond,p_user_miner_id::text,'Miner Level upgrade');
 return jsonb_build_object('ok',true,'level',lvl.level,'hashrate',lvl.hashrate,'upgrade_price_diamond',lvl.upgrade_price_diamond);
end $$;
revoke all on function public.nextgen_upgrade_miner(bigint) from public,anon; grant execute on function public.nextgen_upgrade_miner(bigint) to authenticated;

