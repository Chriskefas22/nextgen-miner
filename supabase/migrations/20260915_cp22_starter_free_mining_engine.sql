-- Deterministic 1..1001 economic E2E test. It is owner-only and uses temporary rows only.
create or replace function public.nextgen_owner_starter_mining_e2e_1001()
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  s public.nextgen_starter_mining_settings%rowtype;
  slot integer;
  expected_free_daily numeric;
  expected_free_30d numeric;
  expected_basic_daily numeric;
  min_reserve numeric;
  failures text[]:=array[]::text[];
  test_uuid uuid:=gen_random_uuid();
  test_miner bigint;
  before_balance numeric:=0;
  after_balance numeric:=0;
  projection_hourly numeric;
  projection_daily numeric;
  projection_30d numeric;
begin
  if not public.nextgen_is_owner() then raise exception 'OWNER_ONLY'; end if;
  select * into s from public.nextgen_starter_mining_settings where id=true;
  expected_free_daily:=s.entry_gpu_hashrate*(s.target_reward_usd_per_1000_hash_day/1000.0);
  expected_free_30d:=expected_free_daily*30;
  expected_basic_daily:=s.fallback_basic_cpu_hashrate*(s.target_reward_usd_per_1000_hash_day/1000.0);
  min_reserve:=expected_free_daily*s.minimum_coverage_days;

  if expected_free_daily<>0.0048 then failures:=array_append(failures,'ENTRY_GPU_DAILY_TARGET_MISMATCH'); end if;
  if expected_basic_daily<>0.0016 then failures:=array_append(failures,'BASIC_CPU_DAILY_TARGET_MISMATCH'); end if;
  if expected_free_30d<>0.144 then failures:=array_append(failures,'ENTRY_GPU_30D_TARGET_MISMATCH'); end if;
  if s.max_free_users<>1000 then failures:=array_append(failures,'FREE_USER_CAP_MISMATCH'); end if;

  -- Slot allocation contract: 1..1000 Entry GPU, 1001 fallback Basic CPU.
  for slot in 1..1001 loop
    if slot<=1000 then test_miner:=3; else test_miner:=2; end if;
    if slot<=1000 and test_miner<>3 then failures:=array_append(failures,'SLOT_'||slot||'_NOT_ENTRY_GPU'); end if;
    if slot=1001 and test_miner<>2 then failures:=array_append(failures,'SLOT_1001_NOT_BASIC_CPU'); end if;
  end loop;

  projection_hourly:=expected_free_daily/24;
  projection_daily:=projection_hourly*24;
  projection_30d:=projection_daily*30;
  if abs(projection_hourly-0.0002)>0.0000000001 then failures:=array_append(failures,'HOURLY_PROJECTION_MISMATCH'); end if;
  if abs(projection_daily-0.0048)>0.0000000001 then failures:=array_append(failures,'DAILY_PROJECTION_MISMATCH'); end if;
  if abs(projection_30d-0.144)>0.0000000001 then failures:=array_append(failures,'THIRTY_DAY_PROJECTION_MISMATCH'); end if;

  -- Reserve thresholds for 1000 fully active Entry GPUs.
  if abs(expected_free_daily*1000-4.8)>0.0000000001 then failures:=array_append(failures,'NETWORK_DAILY_LIABILITY_MISMATCH'); end if;
  if abs(expected_free_30d*1000-144)>0.0000000001 then failures:=array_append(failures,'NETWORK_30D_LIABILITY_MISMATCH'); end if;
  if abs(min_reserve*1000-33.6)>0.0000000001 then failures:=array_append(failures,'NETWORK_7D_RESERVE_MISMATCH'); end if;

  if not exists (select 1 from cron.job where jobname='nextgen-starter-mining-enforcement') then failures:=array_append(failures,'CRON_ENFORCEMENT_JOB_MISSING'); end if;
  if pg_get_function_result('public.nextgen_live_mining_snapshot(text)'::regprocedure)<>'jsonb' then failures:=array_append(failures,'LIVE_SNAPSHOT_SIGNATURE_INVALID'); end if;

  -- Projection sanity under reserve: full reserve => 1x; half reserve => 0.5x; seven-day floor blocks renewal.
  if s.reserve_balance_usd>=expected_free_30d*1000 then
    if abs(least(s.reserve_balance_usd/(expected_free_30d*1000),1)-1)>0.0000001 then failures:=array_append(failures,'FULL_RESERVE_MULTIPLIER_INVALID'); end if;
  end if;

  return jsonb_build_object('success',cardinality(failures)=0,'failures',to_jsonb(failures),'free_slots',1000,'fallback_slot',1001,
    'entry_gpu_hashrate',s.entry_gpu_hashrate,'basic_cpu_hashrate',s.fallback_basic_cpu_hashrate,
    'entry_gpu_daily_usd',expected_free_daily,'entry_gpu_hourly_usd',projection_hourly,'entry_gpu_30d_usd',projection_30d,
    'all_1000_entry_gpu_daily_liability_usd',expected_free_daily*1000,
    'all_1000_entry_gpu_30d_liability_usd',expected_free_30d*1000,
    'all_1000_entry_gpu_minimum_7d_reserve_usd',min_reserve*1000,
    'as_of',now());
end;
$$;
revoke all on function public.nextgen_owner_starter_mining_e2e_1001() from public,anon,authenticated;

