-- Trigger hardens free-bonus level expansion without rewriting existing upgrade/merge functions.
create or replace function public.nextgen_guard_free_bonus_upgrade_trigger()
returns trigger
language plpgsql
security definer
set search_path to ''
as $$
declare old_hash numeric; new_hash numeric; add_daily numeric;
begin
  if coalesce(OLD.reward_class,'standard')='free_bonus' and coalesce(NEW.current_level,OLD.current_level)>OLD.current_level then
    select hashrate into old_hash from public.nextgen_miner_levels where miner_id=OLD.miner_id and level=OLD.current_level;
    select hashrate into new_hash from public.nextgen_miner_levels where miner_id=NEW.miner_id and level=NEW.current_level;
    add_daily:=greatest(new_hash-old_hash,0)*(0.08/1000.0);
    if add_daily>0 then perform public.nextgen_assert_starter_capacity_for_expansion(add_daily); end if;
  end if;
  return NEW;
end;
$$;
