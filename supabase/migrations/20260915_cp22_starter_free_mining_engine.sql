-- CP22 — Starter/Free Mining Reserve + Live Accrual + 24h Recharge Enforcement
-- Production migration. Landing page remains untouched.

create table if not exists public.nextgen_starter_mining_settings (
  id boolean primary key default true,
  enabled boolean not null default true,
  asset text not null default 'USDT',
  campaign_key text not null default 'launch-entry-gpu',
  max_free_users integer not null default 1000 check (max_free_users > 0),
  entry_gpu_hashrate numeric(30,8) not null default 60 check (entry_gpu_hashrate >= 0),
  fallback_basic_cpu_hashrate numeric(30,8) not null default 20 check (fallback_basic_cpu_hashrate >= 0),
  target_reward_usd_per_1000_hash_day numeric(30,18) not null default 0.08 check (target_reward_usd_per_1000_hash_day >= 0),
  target_daily_per_entry_gpu_usd numeric(30,18) not null default 0.0048 check (target_daily_per_entry_gpu_usd >= 0),
  target_coverage_days numeric(20,4) not null default 30 check (target_coverage_days > 0),
  minimum_coverage_days numeric(20,4) not null default 7 check (minimum_coverage_days > 0),
  warning_coverage_days numeric(20,4) not null default 14 check (warning_coverage_days > 0),
  reserve_balance_usd numeric(30,18) not null default 0 check (reserve_balance_usd >= 0),
  settled_out_usd numeric(30,18) not null default 0 check (settled_out_usd >= 0),
  updated_at timestamptz not null default now()
);

insert into public.nextgen_starter_mining_settings(id) values(true)
on conflict(id) do nothing;

alter table public.nextgen_starter_mining_settings enable row level security;
revoke all on public.nextgen_starter_mining_settings from anon, authenticated;
