create or replace function public.nextgen_assert_starter_capacity_for_recharge(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path to ''
as $$
declare
  s public.nextgen_starter_mining_settings%rowtype;
  active_weight numeric:=0;
  projected_daily numeric:=0;
  minimum_reserve numeric:=0;
begin
  if p_user_id is null then raise exception 'USER_REQUIRED'; end if;
  perform pg_advisory_xact_lock(hashtextextended(p_user_id::text||':starter_recharge',20424));
  select * into s from public.nextgen_starter_mining_settings where id=true for update;
  if not s.enabled then raise exception 'STARTER_MINING_DISABLED'; end if;
  if not exists (select 1 from public.nextgen_user_miners where user_id=p_user_id and reward_class='free_bonus' and is_merged=false) then return; end if;
  select coalesce(sum(l.hashrate*greatest(l.efficiency,0)*least(greatest(coalesce(um.energy_percent,0),0),100)/100.0),0)
    into active_weight
  from public.nextgen_user_miners um
  join public.nextgen_miner_levels l on l.miner_id=um.miner_id and l.level=um.current_level
  where um.reward_class='free_bonus' and um.is_merged=false and um.user_id=p_user_id;
  projected_daily:=active_weight*(s.target_reward_usd_per_1000_hash_day/1000.0);
  minimum_reserve:=projected_daily*s.minimum_coverage_days;
  if s.reserve_balance_usd < minimum_reserve then
    raise exception 'STARTER_CAPACITY_BLOCKED';
  end if;
end;
$$;
