-- Compute a server-side live estimate. It never mutates crypto balances.
create or replace function public.nextgen_live_mining_snapshot(p_asset text default 'USDT')
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  uid uuid:=auth.uid();
  asset_code text:=upper(trim(coalesce(p_asset,'USDT')));
  s public.nextgen_starter_mining_settings%rowtype;
  active_hash numeric:=0; free_hash numeric:=0; standard_hash numeric:=0;
  active_miners integer:=0; free_miners integer:=0; standard_miners integer:=0;
  now_ts timestamptz:=now();
  free_rate numeric:=0; standard_rate numeric:=0; capacity_multiplier numeric:=0;
  remaining_session_seconds numeric:=0; live_elapsed_seconds numeric:=0;
  live_usd numeric:=0; live_crypto numeric:=0; hourly_usd numeric:=0; daily_usd numeric:=0; thirty_day_usd numeric:=0;
  selected_rate numeric:=0; selected_rate_updated timestamptz;
  session_started_at timestamptz; session_expires_at timestamptz;
  status text:='PAUSED'; source text:='NONE';
  starter_daily_liability numeric:=0; starter_coverage_days numeric:=0;
begin
  if uid is null then raise exception 'AUTH_REQUIRED'; end if;
  perform public.nextgen_enforce_mining_recharge_state_for_user(uid);
  select * into s from public.nextgen_starter_mining_settings where id=true;
  select r.rate_usd,r.updated_at into selected_rate,selected_rate_updated
  from public.nextgen_exchange_rates r where upper(r.asset)=asset_code
  order by r.updated_at desc limit 1;

  with active as (
    select um.id,um.reward_class,um.last_recharge_at,um.recharge_expires_at,
           l.hashrate,l.efficiency,least(greatest(coalesce(um.energy_percent,0),0),100) energy_percent,
           greatest(extract(epoch from (least(now_ts,um.recharge_expires_at)-greatest(um.last_recharge_at,now_ts-interval '24 hours'))),0) elapsed_seconds
    from public.nextgen_user_miners um
    join public.nextgen_miner_levels l on l.miner_id=um.miner_id and l.level=um.current_level
    where um.user_id=uid and um.is_merged=false and um.status='active' and um.recharge_expires_at>now_ts
  )
  select count(*)::integer,
         count(*) filter(where reward_class='free_bonus')::integer,
         count(*) filter(where reward_class<>'free_bonus' or reward_class is null)::integer,
         coalesce(sum(hashrate*greatest(efficiency,0)*energy_percent/100.0),0),
         coalesce(sum(hashrate*greatest(efficiency,0)*energy_percent/100.0) filter(where reward_class='free_bonus'),0),
         coalesce(sum(hashrate*greatest(efficiency,0)*energy_percent/100.0) filter(where reward_class<>'free_bonus' or reward_class is null),0),
         min(last_recharge_at),max(recharge_expires_at)
  into active_miners,free_miners,standard_miners,active_hash,free_hash,standard_hash,session_started_at,session_expires_at
  from active;

  capacity_multiplier:=case
    when free_hash<=0 then 0
    when free_hash*(s.target_reward_usd_per_1000_hash_day/1000.0)*s.target_coverage_days<=0 then 1
    else least(greatest(s.reserve_balance_usd/(free_hash*(s.target_reward_usd_per_1000_hash_day/1000.0)*s.target_coverage_days),0),1)
  end;
  starter_daily_liability:=free_hash*(s.target_reward_usd_per_1000_hash_day/1000.0)*capacity_multiplier;
  starter_coverage_days:=case when starter_daily_liability>0 then s.reserve_balance_usd/starter_daily_liability else 999999 end;
  free_rate:=case when free_hash>0 then (s.target_reward_usd_per_1000_hash_day/1000.0/86400.0)*capacity_multiplier else 0 end;
  select coalesce(max(p.reward_rate_usd_per_hash_second),0) into standard_rate
  from public.nextgen_mining_daily_pools p
  where upper(p.asset)=asset_code and p.pool_date=timezone('utc',now())::date and p.mining_budget_usd>0 and p.prepared_at is not null;

  if free_hash>0 and s.enabled and s.reserve_balance_usd>0 then
    select coalesce(sum(x.reward_usd),0),coalesce(sum(x.elapsed_seconds),0)
    into live_usd,live_elapsed_seconds
    from (
      select free_rate*(l.hashrate*greatest(l.efficiency,0)*least(greatest(coalesce(um.energy_percent,0),0),100)/100.0) *
             least(greatest(extract(epoch from (least(now_ts,um.recharge_expires_at)-greatest(um.last_recharge_at,now_ts-interval '24 hours'))),0),86400) reward_usd,
             least(greatest(extract(epoch from (least(now_ts,um.recharge_expires_at)-greatest(um.last_recharge_at,now_ts-interval '24 hours'))),0),86400) elapsed_seconds
      from public.nextgen_user_miners um
      join public.nextgen_miner_levels l on l.miner_id=um.miner_id and l.level=um.current_level
      where um.user_id=uid and um.reward_class='free_bonus' and um.is_merged=false and um.status='active' and um.recharge_expires_at>now_ts
    ) x;
    remaining_session_seconds:=greatest(extract(epoch from (session_expires_at-now_ts)),0);
    if selected_rate>0 then live_crypto:=round(live_usd/selected_rate,24); end if;
    hourly_usd:=free_rate*free_hash*3600;
    daily_usd:=free_rate*free_hash*86400;
    thirty_day_usd:=daily_usd*30;
    status:=case when capacity_multiplier<1 then 'ACTIVE_GUARDED' else 'ACTIVE' end;
    source:='STARTER_RESERVE';
  elsif standard_hash>0 and standard_rate>0 then
    select coalesce(sum(x.reward_usd),0),coalesce(sum(x.elapsed_seconds),0)
    into live_usd,live_elapsed_seconds
    from (
      select standard_rate*(l.hashrate*greatest(l.efficiency,0)*least(greatest(coalesce(um.energy_percent,0),0),100)/100.0) *
             least(greatest(extract(epoch from (least(now_ts,um.recharge_expires_at)-greatest(um.last_recharge_at,now_ts-interval '24 hours'))),0),86400) reward_usd,
             least(greatest(extract(epoch from (least(now_ts,um.recharge_expires_at)-greatest(um.last_recharge_at,now_ts-interval '24 hours'))),0),86400) elapsed_seconds
      from public.nextgen_user_miners um
      join public.nextgen_miner_levels l on l.miner_id=um.miner_id and l.level=um.current_level
      where um.user_id=uid and coalesce(um.reward_class,'standard')<>'free_bonus' and um.is_merged=false and um.status='active' and um.recharge_expires_at>now_ts
    ) x;
    remaining_session_seconds:=greatest(extract(epoch from (session_expires_at-now_ts)),0);
    if selected_rate>0 then live_crypto:=round(live_usd/selected_rate,24); end if;
    hourly_usd:=standard_rate*standard_hash*3600;
    daily_usd:=standard_rate*standard_hash*86400;
    thirty_day_usd:=daily_usd*30;
    status:='ACTIVE_POOL';
    source:='FUNDED_POOL';
  elsif active_miners>0 then
    status:=case when free_hash>0 and s.reserve_balance_usd<=0 then 'STARTER_POOL_PAUSED' else 'POOL_PAUSED' end;
  end if;

  return jsonb_build_object(
    'asset',asset_code,'status',status,'source',source,
    'active_miners',active_miners,'free_miners',free_miners,'standard_miners',standard_miners,
    'active_hashrate',active_hash,'free_hashrate',free_hash,'standard_hashrate',standard_hash,
    'capacity_multiplier',capacity_multiplier,'starter_reserve_balance_usd',s.reserve_balance_usd,
    'starter_daily_liability_usd',starter_daily_liability,'starter_coverage_days',starter_coverage_days,
    'reward_rate_usd_per_hash_second',case when source='STARTER_RESERVE' then free_rate else standard_rate end,
    'hourly_usd',hourly_usd,'daily_usd',daily_usd,'thirty_day_usd',thirty_day_usd,
    'estimated_usd',live_usd,'estimated_crypto',live_crypto,'elapsed_seconds',live_elapsed_seconds,
    'remaining_session_seconds',remaining_session_seconds,'session_started_at',session_started_at,
    'recharge_expires_at',session_expires_at,'crypto_rate_usd',coalesce(selected_rate,0),
    'crypto_rate_updated_at',selected_rate_updated,'claim_is_server_settled',true,'as_of',now_ts
  );
end;
$$;
revoke all on function public.nextgen_live_mining_snapshot(text) from public,anon;
grant execute on function public.nextgen_live_mining_snapshot(text) to authenticated;

-- Realize starter accrual into the crypto ledger. This function settles the interval since
-- last_accrual_at, capped by the miner's 24h recharge expiry. It never fabricates provider revenue.
create or replace function public.nextgen_settle_starter_mining_for_user(p_user_id uuid, p_asset text default 'USDT')
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  uid uuid:=p_user_id;
  asset_code text:=upper(trim(coalesce(p_asset,'USDT')));
  s public.nextgen_starter_mining_settings%rowtype;
  er numeric:=0;
  er_updated timestamptz;
  r record;
  start_ts timestamptz;
  end_ts timestamptz;
  secs numeric;
  rate numeric;
  usd numeric;
  crypto_amt numeric;
  total_usd numeric:=0;
  total_crypto numeric:=0;
  existing_id bigint;
  reserve_after numeric;
  rate_capacity_multiplier numeric:=0;
begin
  if uid is null then raise exception 'USER_REQUIRED'; end if;
  perform pg_advisory_xact_lock(hashtextextended(uid::text||':'||asset_code, 20423));
  select * into s from public.nextgen_starter_mining_settings where id=true for update;
  if not s.enabled or s.asset<>asset_code then return jsonb_build_object('success',true,'settled_usd',0,'settled_crypto',0,'reason','STARTER_DISABLED'); end if;
  select r.rate_usd,r.updated_at into er,er_updated from public.nextgen_exchange_rates r where upper(r.asset)=asset_code order by r.updated_at desc limit 1;
  if er is null or er<=0 or er_updated<now()-interval '15 minutes' then
    return jsonb_build_object('success',true,'settled_usd',0,'settled_crypto',0,'reason','ASSET_RATE_STALE');
  end if;
  for r in
    select um.id,um.user_id,um.last_accrual_at,um.last_recharge_at,um.recharge_expires_at,um.status,
           l.hashrate,l.efficiency,least(greatest(coalesce(um.energy_percent,0),0),100) energy_percent
    from public.nextgen_user_miners um
    join public.nextgen_miner_levels l on l.miner_id=um.miner_id and l.level=um.current_level
    where um.user_id=uid and um.reward_class='free_bonus' and um.is_merged=false
    order by um.id
    for update
  loop
    start_ts:=greatest(coalesce(r.last_accrual_at,r.last_recharge_at),coalesce(r.last_recharge_at,r.last_accrual_at));
    end_ts:=least(now(),r.recharge_expires_at);
    if start_ts is null or end_ts<=start_ts then continue; end if;
    secs:=least(greatest(extract(epoch from (end_ts-start_ts)),0),86400);
    -- Rate is capacity-aware and matches the live snapshot. Full target rate requires the
    -- configured target reserve; lower funded coverage transparently throttles the starter rate.
    rate:=(s.target_reward_usd_per_1000_hash_day/1000.0/86400.0);
    select least(greatest(s.reserve_balance_usd / nullif(
      (select coalesce(sum(l2.hashrate*greatest(l2.efficiency,0)*least(greatest(coalesce(um2.energy_percent,0),0),100)/100.0),0)
       from public.nextgen_user_miners um2
       join public.nextgen_miner_levels l2 on l2.miner_id=um2.miner_id and l2.level=um2.current_level
       where um2.reward_class='free_bonus' and um2.is_merged=false
         and um2.status='active' and um2.recharge_expires_at>now()),0)
      * (s.target_reward_usd_per_1000_hash_day/1000.0) * s.target_coverage_days,0),0),1)
      into rate_capacity_multiplier;
    rate:=rate*coalesce(rate_capacity_multiplier,0);
    usd:=round(rate*r.hashrate*greatest(r.efficiency,0)*r.energy_percent/100.0*secs,18);
    if usd<=0 then update public.nextgen_user_miners set last_accrual_at=end_ts where id=r.id; continue; end if;
    if usd>s.reserve_balance_usd-total_usd then usd:=greatest(s.reserve_balance_usd-total_usd,0); end if;
    if usd<=0 then exit; end if;
    crypto_amt:=round(usd/er,24);
    select id into existing_id from public.nextgen_starter_mining_settlements x where x.user_id=uid and x.user_miner_id=r.id and x.asset=asset_code and x.period_start=start_ts and x.period_end=end_ts;
    if existing_id is null then
      insert into public.nextgen_starter_mining_settlements(user_id,user_miner_id,asset,period_start,period_end,elapsed_seconds,hashrate,reward_rate_usd_per_hash_second,allocated_usd,crypto_amount)
      values(uid,r.id,asset_code,start_ts,end_ts,secs,r.hashrate,rate,usd,crypto_amt);
      insert into public.nextgen_crypto_balances(user_id,asset,balance,reserved_balance)
      values(uid,asset_code,crypto_amt,0)
      on conflict(user_id,asset) do update set balance=public.nextgen_crypto_balances.balance+excluded.balance,updated_at=now();
      insert into public.nextgen_crypto_ledger(user_id,asset,direction,amount,usd_value,reference_type,reference_id,note)
      values(uid,asset_code,'mining_reward',crypto_amt,usd,'starter_mining',r.id::text,'24h starter mining accrual settlement');
      insert into public.nextgen_transactions(user_id,tx_type,diamond_delta,usd_delta,asset,crypto_amount,reference_id,note)
      values(uid,'starter_mining_reward',0,usd,asset_code,crypto_amt,r.id::text,'Starter reserve mining settlement');
      insert into public.nextgen_starter_reserve_ledger(event_type,event_amount_usd,balance_after_usd,user_id,user_miner_id,asset,source_reference,note)
      values('SETTLE',usd,greatest(s.reserve_balance_usd-total_usd-usd,0),uid,r.id,asset_code,md5('starter_settle:'||uid::text||':'||r.id::text||':'||start_ts::text||':'||end_ts::text),'Starter mining payout reserve release');
      total_usd:=total_usd+usd;
      total_crypto:=total_crypto+crypto_amt;
    end if;
    update public.nextgen_user_miners set last_accrual_at=end_ts where id=r.id;
  end loop;
  if total_usd>0 then
    reserve_after:=greatest(s.reserve_balance_usd-total_usd,0);
    update public.nextgen_starter_mining_settings set reserve_balance_usd=reserve_after,settled_out_usd=settled_out_usd+total_usd,updated_at=now() where id=true;
  end if;
  return jsonb_build_object('success',true,'asset',asset_code,'settled_usd',total_usd,'settled_crypto',total_crypto,'reserve_balance_usd',case when total_usd>0 then greatest(s.reserve_balance_usd-total_usd,0) else s.reserve_balance_usd end,'rate_usd',er,'rate_updated_at',er_updated);
end;
