-- Make the existing per-miner accrual cursor suitable for the starter engine.
-- The existing column already exists and is server-controlled through SECURITY DEFINER functions.

create or replace function public.nextgen_starter_capacity_snapshot()
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  s public.nextgen_starter_mining_settings%rowtype;
  active_users integer := 0;
  active_miners integer := 0;
  active_free_weight numeric := 0;
  daily_target numeric := 0;
  coverage_days numeric := 0;
  target_reserve numeric := 0;
  minimum_reserve numeric := 0;
  multiplier numeric := 0;
  status text := 'PAUSED';
  claimed_slots integer := 0;
  remaining_slots integer := 0;
begin
  if not public.nextgen_is_owner() then raise exception 'OWNER_ONLY'; end if;
  select * into s from public.nextgen_starter_mining_settings where id=true for update;
  select count(distinct um.user_id),count(*) into active_users,active_miners
  from public.nextgen_user_miners um
  where um.reward_class='free_bonus' and um.is_merged=false and um.status='active' and um.recharge_expires_at>now();
  select coalesce(sum(l.hashrate*greatest(l.efficiency,0)*least(greatest(coalesce(um.energy_percent,0),0),100)/100.0),0)
    into active_free_weight
  from public.nextgen_user_miners um
  join public.nextgen_miner_levels l on l.miner_id=um.miner_id and l.level=um.current_level
  where um.reward_class='free_bonus' and um.is_merged=false and um.status='active' and um.recharge_expires_at>now();
  daily_target := active_free_weight*(s.target_reward_usd_per_1000_hash_day/1000.0);
  target_reserve := daily_target*s.target_coverage_days;
  minimum_reserve := daily_target*s.minimum_coverage_days;
  coverage_days := case when daily_target>0 then s.reserve_balance_usd/daily_target else 999999 end;
  multiplier := case when target_reserve<=0 then 1 else least(greatest(s.reserve_balance_usd/target_reserve,0),1) end;
  status := case
    when not s.enabled then 'DISABLED'
    when active_users=0 then 'IDLE'
    when s.reserve_balance_usd<=0 then 'PAUSED_NO_RESERVE'
    when coverage_days < s.minimum_coverage_days then 'CAPACITY_GUARDED'
    when coverage_days < s.warning_coverage_days then 'WARNING'
    else 'HEALTHY'
  end;
  select coalesce(c.claimed_slots,0),greatest(coalesce(c.total_slots,0)-coalesce(c.claimed_slots,0),0)
    into claimed_slots,remaining_slots
  from public.nextgen_registration_bonus_campaigns c where c.campaign_key=s.campaign_key;
  return jsonb_build_object(
    'enabled',s.enabled,
    'asset',s.asset,
    'campaign_key',s.campaign_key,
    'max_free_users',s.max_free_users,
    'claimed_slots',claimed_slots,
    'remaining_slots',remaining_slots,
    'active_free_users',active_users,
    'active_free_miners',active_miners,
    'active_free_weighted_hash',active_free_weight,
    'target_daily_liability_usd',daily_target,
    'target_30d_reserve_usd',target_reserve,
    'minimum_7d_reserve_usd',minimum_reserve,
    'reserve_balance_usd',s.reserve_balance_usd,
    'settled_out_usd',s.settled_out_usd,
    'coverage_days',coverage_days,
    'capacity_multiplier',multiplier,
    'status',status,
    'target_reward_usd_per_1000_hash_day',s.target_reward_usd_per_1000_hash_day,
    'target_daily_per_entry_gpu_usd',s.target_daily_per_entry_gpu_usd,
    'target_coverage_days',s.target_coverage_days,
    'warning_coverage_days',s.warning_coverage_days,
    'minimum_coverage_days',s.minimum_coverage_days,
    'as_of',now()
  );
end;
$$;
revoke all on function public.nextgen_starter_capacity_snapshot() from public,anon;
grant execute on function public.nextgen_starter_capacity_snapshot() to authenticated;

create or replace function public.nextgen_owner_fund_starter_reserve(p_amount_usd numeric, p_note text)
returns jsonb
language plpgsql
security definer
set search_path to ''
as $$
declare
  s public.nextgen_starter_mining_settings%rowtype;
  new_balance numeric;
begin
  if not public.nextgen_is_owner() then raise exception 'OWNER_ONLY'; end if;
  if p_amount_usd is null or p_amount_usd<=0 then raise exception 'INVALID_AMOUNT'; end if;
  if p_note is null or length(trim(p_note))<3 then raise exception 'NOTE_REQUIRED'; end if;
  perform pg_advisory_xact_lock(hashtext('nextgen_starter_reserve'));
  select * into s from public.nextgen_starter_mining_settings where id=true for update;
  new_balance:=s.reserve_balance_usd+p_amount_usd;
  update public.nextgen_starter_mining_settings set reserve_balance_usd=new_balance,updated_at=now() where id=true;
  insert into public.nextgen_starter_reserve_ledger(event_type,event_amount_usd,balance_after_usd,asset,source_reference,note)
  values('FUND',p_amount_usd,new_balance,s.asset,md5('fund:'||now()::text||':'||p_amount_usd::text),left(trim(p_note),500));
  return jsonb_build_object('success',true,'funded_usd',p_amount_usd,'reserve_balance_usd',new_balance);
end;
$$;
revoke all on function public.nextgen_owner_fund_starter_reserve(numeric,text) from public,anon,authenticated;

-- Normalize expired miners immediately. This is called by user-facing snapshots/actions and by cron.
create or replace function public.nextgen_enforce_mining_recharge_state_for_user(p_user_id uuid)
returns integer
language plpgsql
security definer
set search_path to ''
as $$
declare n integer;
begin
  if p_user_id is null then raise exception 'USER_REQUIRED'; end if;
  update public.nextgen_user_miners
  set status='paused'
  where user_id=p_user_id and is_merged=false and status='active' and recharge_expires_at<=now();
  get diagnostics n=row_count;
  return n;
end;
$$;
revoke all on function public.nextgen_enforce_mining_recharge_state_for_user(uuid) from public,anon,authenticated;

